import { CanActivate, ExecutionContext, ForbiddenException, Inject, Injectable, UnauthorizedException } from '@nestjs/common';
import { REPOSITORY_TOKENS } from '../../database/database.module';
import { JsonRepository } from '../../database/json-repository';

@Injectable()
export class AccountAccessGuard implements CanActivate {
  constructor(
    @Inject(REPOSITORY_TOKENS.USERS) private readonly users: JsonRepository<any>,
    @Inject(REPOSITORY_TOKENS.LEARNERS) private readonly learners: JsonRepository<any>,
    @Inject(REPOSITORY_TOKENS.INSTRUCTORS) private readonly instructors: JsonRepository<any>,
    @Inject(REPOSITORY_TOKENS.ORGANIZATIONS) private readonly organizations: JsonRepository<any>,
  ) {}

  async canActivate(context: ExecutionContext) {
    const request = context.switchToHttp().getRequest();
    const path = request.path || request.url || '';
    const tokenId=String(request.headers.authorization||'').replace(/^Bearer\s+/i,'').match(/^jwt-token-(.+)-\d+$/)?.[1];
    const legacyId=request.headers['x-user-id']||tokenId;
    if(legacyId){const accounts=await this.users.find();const canonical=accounts.find(a=>Array.isArray((a as any).legacyUserIds)&&(a as any).legacyUserIds.includes(legacyId));if(canonical)request.headers['x-user-id']=canonical.id;}

    // Sign-in and public credential verification must remain reachable.
    if (/\/public\/(?:landing|demo-credentials)\/?$/.test(path) || /\/auth\//.test(path) || /\/certificates\/verify\//.test(path)) return true;
    const method=String(request.method||'GET').toUpperCase();
    const cleanPath=path.replace(/^\/api/,'').split('?')[0].replace(/\/$/,'');
    const createAccount=method==='POST'&&['/users','/learners','/organizations','/admin/accounts'].includes(cleanPath);
    if(createAccount)throw new ForbiddenException('Accounts are created through registration, not platform administration.');
    const learnerLegacyRoute=/^\/quizzes(?:\/|$)/.test(cleanPath)||/^\/disputes(?:\/|$)/.test(cleanPath)&&cleanPath!=='/disputes/my';
    if(learnerLegacyRoute){const legacyId=request.headers['x-user-id'];const actor=legacyId?await this.users.findById(legacyId):null;if(['student','learner'].includes(String(actor?.role||'').toLowerCase()))throw new ForbiddenException('Use your learner assessment and support endpoints to access your own records.');}
    const protectedInstructorCreate=method==='POST'&&cleanPath==='/instructors';
    const protectedProfileChange=['PATCH','PUT'].includes(method)&&/^\/(organizations|learners|instructors)\/[^/]+(?:\/verify)?$/.test(cleanPath);
    const protectedProfileDelete=method==='DELETE'&&/^\/(organizations|learners)\/[^/]+$/.test(cleanPath);
    const protectedUserChange=['PATCH','PUT','DELETE'].includes(method)&&/^\/users\/[^/]+$/.test(cleanPath);
    const protectedInstructorDelete=method==='DELETE'&&/^\/instructors\/[^/]+$/.test(cleanPath);
    const protectedPaymentChange=['PATCH','PUT','DELETE'].includes(method)&&/^\/(admin\/payments|payments\/transactions)\//.test(cleanPath);
    if(method==='POST'&&['/notifications','/workspace/notifications','/users/activity'].includes(cleanPath))throw new ForbiddenException('Notifications are generated by workflow events.');
    if(method==='POST'&&['/admin/payouts','/payments/transactions'].includes(cleanPath))throw new ForbiddenException('Financial records are created by the payment workflow.');
    if(protectedPaymentChange)throw new ForbiddenException('Payment records are read-only.');
    const suppliedId=request.headers['x-user-id'];
    const suppliedToken=String(request.headers.authorization||'').replace(/^Bearer\s+/i,'');
    const actingId=suppliedId||suppliedToken.match(/^jwt-token-(.+)-\d+$/)?.[1];
    if(protectedInstructorCreate||protectedProfileChange||protectedInstructorDelete||protectedUserChange||protectedProfileDelete){
      const actor=actingId?await this.users.findById(actingId):null;
      const role=String(actor?.role||'').toLowerCase().replace(/[\s_-]/g,'');
      if(protectedUserChange){
        if(!['admin','superadmin'].includes(role))throw new ForbiddenException('Platform administrator access is required.');
        request.headers['x-role']=role;
        if(method!=='DELETE'&&Object.keys(request.body||{}).some(key=>key!=='status'))throw new ForbiddenException('Account details can only be edited by their owner.');
      }
      if(protectedInstructorDelete)throw new ForbiddenException('Instructor accounts cannot be deleted here. Affiliation and access are managed through the organization workflow.');
      if(protectedInstructorCreate&&role!=='organization')throw new ForbiddenException('Only an organization can add instructors.');
      if((protectedProfileChange||protectedInstructorDelete||protectedProfileDelete)&&['admin','superadmin'].includes(role))throw new ForbiddenException('Platform administrators cannot edit organization, learner or instructor profiles, or delete instructors.');
    }
    const token = String(request.headers.authorization || '').replace(/^Bearer\s+/i, '');
    if (!token) return true;
    const id = request.headers['x-user-id'] || token.match(/^jwt-token-(.+)-\d+$/)?.[1];
    if (!id) return true;
    const records = await Promise.all([
      this.users.findById(id), this.learners.findById(id),
      this.instructors.findById(id), this.organizations.findById(id),
    ]);
    const account = records.find(Boolean);
    if (!account) throw new UnauthorizedException('This account no longer exists. Please sign in again.');
    if (account.status === 'Suspended') throw new ForbiddenException('This account is suspended.');
    return true;
  }
}
